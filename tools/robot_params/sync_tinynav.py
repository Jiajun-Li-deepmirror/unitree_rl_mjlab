#!/usr/bin/env python3
"""sync_tinynav.py [--tinynav DIR] [ROBOT ...] (go2-depth 2026-11-12, doc/redesign.md step 2): tinynav-sim's robot
models aligned with unitree_ros as the training's are (model=uros, src/assets/robots/uros.py), so the tinynav tier
judges a policy on the physics it trained on.

For each robot, from tinynav-sim's own model (assets/<r>/<r>.xml; "go2_pie": assets/go2/go2_pie.xml, the PIE plant's)
it writes <name>_uros.xml beside it:
  - every body's <inertial> from our src/assets/robots/unitree_<r>/xmls/<r>_uros.xml (same body names; the body
    positions are checked equal),
  - every <general> / <motor> / <position> actuator's forcerange from the aligned torque limits (the PIE Go2 has no
    actuators in its file: tinynav-sim's plant takes them from sim/contract.py, with TNSIM_MODEL=uros from
    JOINT_EFFORT_LIMIT_UROS there),
  - the leg joints' friction loss and damping at the middle of the training's randomization
    (src/tasks/unified/teacher_env.py JOINT_FRICTION_SHARE / JOINT_DAMPING_SHARE x the joint's torque limit).
tinynav-sim loads them with TNSIM_MODEL=uros (sim/plant.py, sim/robots.py); without it, as before.
"""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

DEFAULT_TN = Path("/home/dm/.cache/go2-depth-work/tnsim-wheeled/mujoco")
SOURCES = {"go2": "go2/go2.xml", "go2_pie": "go2/go2_pie.xml", "go2w": "go2w/go2w.xml", "as2": "as2/as2.xml", "as2w": "as2w/as2w.xml",
           "b2": "b2/b2.xml", "b2w": "b2w/b2w.xml"}
CONSTANTS = {"go2": "GO2", "go2w": "GO2W", "as2": "As2", "as2w": "As2W", "b2": "B2", "b2w": "B2W"}


def efforts(robot: str) -> dict[str, float]:
  """Group (hip / thigh / calf / wheel) -> the aligned torque limit."""
  import importlib

  from src.assets.robots import uros

  mod = importlib.import_module(f"src.assets.robots.unitree_{robot}.{robot}_constants")
  out = {}
  for g in ("hip", "thigh", "calf", "wheel"):
    cfg = getattr(mod, f"{CONSTANTS[robot]}_ACTUATOR_{g.upper()}", None)
    if cfg is not None:
      out[g] = float(uros.ACTUATORS.get(robot, {}).get(g, {}).get("effort_limit", cfg.effort_limit))
  return out


def group(name: str) -> str | None:
  return next((g for g in ("wheel", "calf", "thigh", "hip") if g in name), None)


def build(robot: str, tn: Path) -> Path:
  from src.tasks.unified.teacher_env import JOINT_DAMPING_SHARE, JOINT_FRICTION_SHARE

  src = tn / "assets" / SOURCES[robot]
  base = robot.split("_")[0]   # go2_pie: the PIE Go2 model, the Go2's parameters
  ours = ROOT / "src" / "assets" / "robots" / f"unitree_{base}" / "xmls" / f"{base}_uros.xml"
  dst = src.with_name(src.stem + "_uros.xml")
  text = src.read_text()
  tree = ET.ElementTree(ET.fromstring(text))
  ob = {b.get("name"): b for b in ET.parse(ours).getroot().iter("body")}
  eff = efforts(base)
  n_in = 0
  for body in tree.getroot().iter("body"):
    name = body.get("name")
    if name not in ob:
      raise SystemExit(f"sync_tinynav: {robot} body {name} not in {ours.name}")
    pa, pb = body.get("pos"), ob[name].get("pos")
    if pa and pb and np.abs(np.array(pa.split(), float) - np.array(pb.split(), float)).max() > 2e-3:
      raise SystemExit(f"sync_tinynav: {robot} body {name} position differs ({pa} vs {pb})")
    new = ob[name].find("inertial")
    old = body.find("inertial")
    if new is None:
      continue
    idx = list(body).index(old) if old is not None else 0
    if old is not None:
      body.remove(old)
    body.insert(idx, ET.fromstring(ET.tostring(new)))
    n_in += 1
  n_act = 0
  for tag in ("general", "motor", "position"):
    for a in tree.getroot().iter(tag):
      g = group(a.get("joint", "") or a.get("name", ""))
      if g in eff and a.get("forcerange") is not None:
        a.set("forcerange", f"{-eff[g]:g} {eff[g]:g}")
        n_act += 1
  n_j = 0
  for j in tree.getroot().iter("joint"):
    g = group(j.get("name", ""))
    if g in ("hip", "thigh", "calf") and g in eff:
      j.set("frictionloss", f"{0.5 * JOINT_FRICTION_SHARE * eff[g]:.4g}")
      j.set("damping", f"{0.5 * JOINT_DAMPING_SHARE[g] * eff[g]:.4g}")
      n_j += 1
  head = re.match(r"\s*(<\?xml[^>]*\?>)?", text).group(0) or ""
  body_txt = ET.tostring(tree.getroot(), encoding="unicode")
  dst.write_text(head + f"<!-- {dst.name}: generated by unitree_rl_mjlab tools/robot_params/sync_tinynav.py from {src.name} "
                 f"(inertials, torque limits and joint friction / damping aligned with unitree_ros, as the training's "
                 f"model=uros). Do not edit by hand. -->\n" + body_txt + "\n")
  print(f"{robot}: {dst} ({n_in} inertials, {n_act} actuator limits, {n_j} leg joints)")
  return dst


def main(argv: list[str]) -> int:
  p = argparse.ArgumentParser()
  p.add_argument("--tinynav", type=Path, default=DEFAULT_TN, help="tinynav-sim's mujoco/ directory")
  p.add_argument("robots", nargs="*", default=["go2", "go2_pie", "go2w"])
  a = p.parse_args(argv)
  for r in a.robots:
    build(r, a.tinynav)
  return 0


if __name__ == "__main__":
  sys.exit(main(sys.argv[1:]))
