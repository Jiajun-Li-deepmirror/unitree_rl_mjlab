"""Build an output/<video>/deploy/<video>/ folder from a training run.

The deploy.yaml parameters (default joint pose = action offset and joint_pos_rel
reference, action scale, PD gains) must match the env the policy was trained
in. Copying another motion's deploy.yaml is NOT safe: the old upstream
dance1_subject2 example was trained with a different default pose
(knee 0.30, hip pitch -0.10, elbow 0.87) than this repo's tracking env, which
uses mjlab's asset-zoo G1 (knee 0.669, hip pitch -0.312, elbow 0.60) -- up to
0.37 rad of offset error on every joint target. This script reads the values
from the metadata the training runner attaches to the run's <run>.onnx.

Usage:
  python src/unitree_rl_mjlab/scripts/make_deploy_folder.py --run-dir output/<video>/training/<run> \
      --motion output/<video>/<video>.npz \
      --out output/<video>/deploy/<video>
"""
import argparse
import pathlib
import shutil

import onnx
from project_paths import motion_output_dir

SDK_JOINT_ORDER = [
  "left_hip_pitch_joint", "left_hip_roll_joint", "left_hip_yaw_joint", "left_knee_joint",
  "left_ankle_pitch_joint", "left_ankle_roll_joint", "right_hip_pitch_joint",
  "right_hip_roll_joint", "right_hip_yaw_joint", "right_knee_joint", "right_ankle_pitch_joint",
  "right_ankle_roll_joint", "waist_yaw_joint", "waist_roll_joint", "waist_pitch_joint",
  "left_shoulder_pitch_joint", "left_shoulder_roll_joint", "left_shoulder_yaw_joint",
  "left_elbow_joint", "left_wrist_roll_joint", "left_wrist_pitch_joint", "left_wrist_yaw_joint",
  "right_shoulder_pitch_joint", "right_shoulder_roll_joint", "right_shoulder_yaw_joint",
  "right_elbow_joint", "right_wrist_roll_joint", "right_wrist_pitch_joint", "right_wrist_yaw_joint",
]
# training observation term -> (C++ deploy term, params, dim)
OBS_MAP = {
  "command": ("motion_command", "{command_name: motion}", 58),
  "motion_anchor_ori_b": ("motion_anchor_ori_b", "{command_name: motion}", 6),
  "base_ang_vel": ("base_ang_vel", "{}", 3),
  "joint_pos": ("joint_pos_rel", "{}", 29),
  "joint_vel": ("joint_vel_rel", "{}", 29),
  "actions": ("last_action", "{}", 29),
}


def fmt(vals, digits=6):
  return "[" + ", ".join(f"{float(v):.{digits}g}" for v in vals) + "]"


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--run-dir", required=True)
  ap.add_argument("--motion", required=True)
  ap.add_argument("--out", help="default: output/<video>/deploy/<video>")
  ap.add_argument("--step-dt", type=float, default=0.02)
  args = ap.parse_args()

  run = pathlib.Path(args.run_dir)
  meta_onnx = run / f"{run.name}.onnx"
  meta = {p.key: p.value for p in onnx.load(str(meta_onnx), load_external_data=False).metadata_props}
  names = meta["joint_names"].split(",")
  if names != SDK_JOINT_ORDER:
    raise SystemExit("training joint order differs from the SDK motor order; "
                     "joint_ids_map would need to be computed -- not handled here")
  nums = {k: [float(x) for x in meta[k].split(",")]
          for k in ("joint_stiffness", "joint_damping", "default_joint_pos", "action_scale")}
  obs_names = meta["observation_names"].split(",")
  unknown = [o for o in obs_names if o not in OBS_MAP]
  if unknown:
    raise SystemExit(f"no C++ deploy term for training observations {unknown}")

  lines = [
    f"# generated by scripts/make_deploy_folder.py from {meta_onnx}",
    f"joint_ids_map: {list(range(len(names)))}",
    f"step_dt: {args.step_dt}",
    f"stiffness: {fmt(nums['joint_stiffness'])}",
    f"damping:   {fmt(nums['joint_damping'])}",
    f"default_joint_pos: {fmt(nums['default_joint_pos'])}",
    "commands: {}",
    "actions:",
    "  JointPositionAction:",
    "    clip: null",
    "    joint_names: [.*]",
    f"    scale: {fmt(nums['action_scale'])}",
    f"    offset: {fmt(nums['default_joint_pos'])}",
    "    joint_ids: null",
    "observations:",
  ]
  for o in obs_names:  # order matters: the C++ side concatenates in yaml order
    term, params, dim = OBS_MAP[o]
    lines += [f"  {term}:", f"    params: {params}", "    clip: null",
              f"    scale: {fmt([1.0] * dim)}", "    history_length: 1"]

  out = pathlib.Path(args.out) if args.out else motion_output_dir(args.motion) / "deploy" / pathlib.Path(args.motion).stem
  (out / "params").mkdir(parents=True, exist_ok=True)
  (out / "exported").mkdir(parents=True, exist_ok=True)
  (out / "params" / "deploy.yaml").write_text("\n".join(lines) + "\n")
  motion = pathlib.Path(args.motion)
  shutil.copy(motion, out / "params" / motion.name)
  for f in ("policy.onnx", "policy.onnx.data"):
    if (run / f).exists():
      shutil.copy(run / f, out / "exported" / f)
  print(f"wrote {out} (default_joint_pos/action offset taken from the training run)")


if __name__ == "__main__":
  main()
